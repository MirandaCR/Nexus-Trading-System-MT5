"""
Strategies router — Strategy Lab proxy + MQL5 EA template builder.

The dashboard talks exclusively to nexus-api (port 8000). This router
forwards CRUD calls to nexus-agents (port 8004) so the registry remains
the single source of truth, and assembles the MQL5 Expert Advisor file
on the server so the frontend never has to keep that template in sync.
"""
from __future__ import annotations

import os
from typing import Any

import httpx

from ..http_client import new_client
import structlog
from fastapi import APIRouter, HTTPException, status

from shared.constants import SERVICE_PORTS

logger = structlog.get_logger(__name__)

router = APIRouter(prefix="/api/strategies", tags=["strategies"])

AGENTS_BASE = os.getenv(
    "NEXUS_AGENTS_URL",
    f"http://127.0.0.1:{SERVICE_PORTS['nexus-agents']}",
).rstrip("/")


# ── Helpers ──────────────────────────────────────────────────────────────────


async def _proxy(method: str, path: str, **kwargs) -> Any:
    url = f"{AGENTS_BASE}{path}"
    async with new_client(timeout=30) as client:
        try:
            resp = await client.request(method, url, **kwargs)
        except httpx.RequestError as exc:
            raise HTTPException(
                status.HTTP_502_BAD_GATEWAY,
                f"Agents service unreachable: {exc}",
            )
    if resp.status_code >= 400:
        try:
            detail = resp.json().get("detail", resp.text)
        except Exception:
            detail = resp.text
        raise HTTPException(resp.status_code, detail or resp.reason_phrase)
    if not resp.content:
        return {}
    try:
        return resp.json()
    except Exception:
        return {"raw": resp.text}


# ── REST surface ─────────────────────────────────────────────────────────────


@router.get("")
async def list_strategies(status: str | None = None) -> Any:
    return await _proxy("GET", "/api/strategies", params={"status": status} if status else None)


@router.get("/research/log")
async def research_log(limit: int = 25) -> Any:
    return await _proxy("GET", "/api/strategies/research/log", params={"limit": limit})


@router.post("/research")
async def trigger_research(payload: dict[str, Any] | None = None) -> Any:
    return await _proxy(
        "POST",
        "/api/strategies/research",
        json=payload or {"n": 2},
    )


@router.get("/{strategy_id}")
async def get_strategy(strategy_id: str) -> Any:
    return await _proxy("GET", f"/api/strategies/{strategy_id}")


@router.post("/{strategy_id}/reevaluate")
async def reevaluate(strategy_id: str) -> Any:
    return await _proxy("POST", f"/api/strategies/{strategy_id}/reevaluate")


@router.put("/{strategy_id}/status")
async def update_status(strategy_id: str, body: dict[str, Any]) -> Any:
    return await _proxy(
        "PUT",
        f"/api/strategies/{strategy_id}/status",
        json=body,
    )


@router.get("/{strategy_id}/mql5", response_class=None)
async def export_mql5(strategy_id: str) -> dict[str, Any]:
    """Build a fully-formed MQL5 EA template for a strategy."""
    raw = await _proxy("GET", f"/api/strategies/{strategy_id}")
    code = build_mql5_expert(raw)
    fname = f"Nexus_{raw.get('id','strategy')}_{(raw.get('short_name') or 'strategy').replace(' ','_')}.mq5"
    return {"id": raw.get("id"), "filename": fname, "mql5": code}


# ── MQL5 EA template ─────────────────────────────────────────────────────────


def build_mql5_expert(spec: dict[str, Any]) -> str:
    """Return a complete MQL5 EA source for *spec*.

    The signal block (``GetDirection`` / ``GetConviction``) is sourced from
    the strategy record; everything else (risk parameters, partials, time
    exit, news blackout) is provided by a stable template so the EA is
    immediately compilable in MetaEditor.
    """
    name = (spec.get("name") or "Nexus Strategy").replace('"', "'")
    sid = spec.get("id", "strategy")
    description = (spec.get("description") or "").replace("\n", " ").replace('"', "'")[:200]
    signal_code = spec.get("mql5_signal_code") or _DEFAULT_SIGNAL
    pairs = ",".join(spec.get("pairs", []) or ["EURUSD"])
    tfs = ",".join(spec.get("timeframes", []) or ["H1"])
    agents = ",".join(spec.get("agents", []) or [])

    return _TEMPLATE.format(
        name=name,
        sid=sid,
        description=description,
        signal=signal_code.strip(),
        pairs=pairs,
        timeframes=tfs,
        agents=agents,
    )


_DEFAULT_SIGNAL = """// Default fallback signal — please customise
int GetDirection() { return 0; }
int GetConviction() { return 0; }
"""

_TEMPLATE = """//+------------------------------------------------------------------+
//|  {name}  ({sid})                                                  |
//|  Generated by Nexus Trader · Strategy Lab                          |
//|  {description}                                                     |
//|  Pairs: {pairs}                                                    |
//|  Timeframes: {timeframes}                                          |
//|  Agents involved: {agents}                                          |
//+------------------------------------------------------------------+
#property strict
#property version   "1.00"
#property copyright "Nexus Trader"
#property description "Auto-generated EA from Nexus Strategy Lab"

#include <Trade/Trade.mqh>
CTrade Trade;

input double InpRiskPercent       = 1.5;   // Risk % of equity per trade
input double InpATRMultSL         = 1.5;   // SL = ATR x multiplier
input double InpRRMultTP1         = 1.0;   // TP1 = SL * mult (1R)
input double InpRRMultTP2         = 1.5;   // TP2 = SL * mult (1.5R)
input int    InpMaxOpenPositions  = 3;
input int    InpATRPeriod         = 14;
input int    InpMagic             = 90210;
input int    InpMaxHoldMinutes    = 60;
input bool   InpAvoidHighImpactNews = true;
input int    InpMinConvictionPct  = 60;

datetime g_lastBarTime = 0;
ulong    g_openTickets[];

int OnInit() {{
   Trade.SetExpertMagicNumber(InpMagic);
   Trade.SetTypeFilling(ORDER_FILLING_IOC);
   Trade.SetMarginMode();
   return INIT_SUCCEEDED;
}}

void OnTick() {{
   datetime t = iTime(_Symbol, PERIOD_CURRENT, 0);
   if (t == g_lastBarTime) {{ ManageOpenPositions(); return; }}
   g_lastBarTime = t;

   ManageOpenPositions();
   if (CountOpen() >= InpMaxOpenPositions) return;

   int conv = GetConviction();
   if (conv < InpMinConvictionPct) return;

   int dir = GetDirection();
   if (dir == 0) return;

   if (InpAvoidHighImpactNews && InHighImpactWindow()) return;

   double atr = iATR(_Symbol, PERIOD_CURRENT, InpATRPeriod, 0);
   if (atr <= 0) return;

   double slDist = atr * InpATRMultSL;
   double price  = (dir > 0) ? SymbolInfoDouble(_Symbol, SYMBOL_ASK)
                             : SymbolInfoDouble(_Symbol, SYMBOL_BID);
   double sl     = (dir > 0) ? price - slDist : price + slDist;
   double tp1    = (dir > 0) ? price + slDist * InpRRMultTP1
                             : price - slDist * InpRRMultTP1;

   double lots = ComputeLots(slDist);
   if (lots <= 0) return;

   if (dir > 0) Trade.Buy(lots,  _Symbol, price, sl, tp1, "Nexus");
   else         Trade.Sell(lots, _Symbol, price, sl, tp1, "Nexus");
}}

double ComputeLots(double slDist) {{
   double equity = AccountInfoDouble(ACCOUNT_EQUITY);
   double risk   = equity * InpRiskPercent / 100.0;
   double tickValue = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_VALUE);
   double tickSize  = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_SIZE);
   if (tickSize == 0) return 0;
   double valuePerLot = (slDist / tickSize) * tickValue;
   if (valuePerLot <= 0) return 0;
   double lots = risk / valuePerLot;
   double minLot = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_MIN);
   double step   = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_STEP);
   if (step > 0) lots = MathFloor(lots / step) * step;
   return MathMax(minLot, lots);
}}

void ManageOpenPositions() {{
   for (int i = PositionsTotal() - 1; i >= 0; --i) {{
      ulong ticket = PositionGetTicket(i);
      if (!PositionSelectByTicket(ticket)) continue;
      if (PositionGetInteger(POSITION_MAGIC) != InpMagic) continue;

      datetime opened = (datetime)PositionGetInteger(POSITION_TIME);
      if ((TimeCurrent() - opened) > InpMaxHoldMinutes * 60) {{
         Trade.PositionClose(ticket);
         continue;
      }}

      double entry = PositionGetDouble(POSITION_PRICE_OPEN);
      double sl    = PositionGetDouble(POSITION_SL);
      double tp    = PositionGetDouble(POSITION_TP);
      ENUM_POSITION_TYPE side = (ENUM_POSITION_TYPE)PositionGetInteger(POSITION_TYPE);
      double price = (side == POSITION_TYPE_BUY) ? SymbolInfoDouble(_Symbol, SYMBOL_BID)
                                                 : SymbolInfoDouble(_Symbol, SYMBOL_ASK);

      // Move to break-even after 1R
      double r = MathAbs(entry - sl);
      if (r > 0) {{
         double progress = (side == POSITION_TYPE_BUY) ? (price - entry) : (entry - price);
         if (progress >= r * 0.9 && (sl == 0 || (side == POSITION_TYPE_BUY ? sl < entry : sl > entry))) {{
            Trade.PositionModify(ticket, entry, tp);
         }}
      }}
   }}
}}

int CountOpen() {{
   int count = 0;
   for (int i = 0; i < PositionsTotal(); ++i) {{
      ulong ticket = PositionGetTicket(i);
      if (!PositionSelectByTicket(ticket)) continue;
      if (PositionGetInteger(POSITION_MAGIC) == InpMagic) ++count;
   }}
   return count;
}}

bool InHighImpactWindow() {{
   // Stub: integrate Nexus calendar feed via WebRequest if needed
   return false;
}}

//+------------------------------------------------------------------+
//|  Strategy-specific signal block                                    |
//+------------------------------------------------------------------+
{signal}
"""


